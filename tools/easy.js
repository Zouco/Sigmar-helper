// Builds easy.js (simple wording, English + Greek) from tools/easy-src/<Army>.json.
// Entries are keyed by "Ability name" or "Holder::Ability name" (holder = unit, formation, lore...).
// The built file keys each entry by a hash of the ORIGINAL rules text, so if the rules change
// after a data refresh the app falls back to the official text instead of showing a stale summary.
// Run: node tools/easy.js   (prints which abilities still have no easy wording)
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const ARMIES = new Function(fs.readFileSync(path.join(root, "armies.js"), "utf8") + ";return ARMIES")();
const hash = (s) => { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h * 33) ^ s.charCodeAt(i)) >>> 0; return h.toString(36); };

const out = {}; let total = 0, done = 0;
const missingByArmy = {};
for (const army of ARMIES) {
  const file = path.join(__dirname, "easy-src", army.name + ".json");
  const src = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : {};
  const used = new Set(), missing = [];
  const take = (holder, ab) => {
    if (!ab || !ab.text) return;
    total++;
    const k = [holder + "::" + ab.name, ab.name].find((x) => src[x]);
    if (!k) { missing.push((holder ? holder + " :: " : "") + ab.name); return; }
    used.add(k); done++;
    out[hash(ab.text)] = { en: src[k].en, el: src[k].el };
  };
  (army.abilities || []).forEach((a) => take("", a));
  (army.formations || []).forEach((f) => (f.abilities || []).forEach((a) => take(f.name, a)));
  (army.units || []).forEach((u) => (u.abilities || []).forEach((a) => take(u.name, a)));
  (army.manifestations || []).forEach((m) => (m.abilities || []).forEach((a) => take(m.name, a)));
  (army.enhancements || []).forEach((g) => (g.abilities || []).forEach((a) => take(g.name, a)));
  const unused = Object.keys(src).filter((k) => !used.has(k));
  missingByArmy[army.name] = missing;
  console.log(`${army.name}: ${army.name in missingByArmy ? "" : ""}${missing.length} missing` + (unused.length ? `, unused keys: ${unused.join(" | ")}` : ""));
}
fs.writeFileSync(path.join(root, "easy.js"), "// GENERATED by tools/easy.js from tools/easy-src. Do not edit by hand.\nconst EASY = " + JSON.stringify(out) + ";\n");
console.log(`easy.js written: ${Object.keys(out).length} entries, ${done}/${total} abilities covered`);
if (process.argv[2]) console.log((missingByArmy[process.argv[2]] || []).join("\n"));
